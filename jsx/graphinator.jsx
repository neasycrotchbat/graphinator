/* Graphinator — ExtendScript chart builder.
 *
 * Called from the CEP panel via evalScript. Builds animated bar / line / pie
 * charts as native shape + text layers in the active comp.
 *
 * The hybrid contract:
 *   - The PANEL owns the data, chart type and number formatting. Pressing
 *     Update deletes every layer tagged GRAPHINATOR_ITEM and rebuilds it.
 *   - The ">> GRAPH CONTROLLER <<" null owns colors, animation timing and
 *     scale as LIVE effect controls; every generated layer derives from it
 *     via expressions. On Update the controller (and any tweaks made to it)
 *     is preserved — only its data blob and build markers are refreshed.
 *
 * Geometry is authored for a 1920x1080 comp (chart ≈ 75% of frame, wider
 * than tall for bar/line) and scaled proportionally for other comp sizes.
 */

