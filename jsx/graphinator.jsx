  var EASING_INDEX = { linear: 1, smooth: 2, overshoot: 3, bounce: 4 };

  // ================================================================ utils

  function parseJSON(text) {
    // Crockford-style validation, then eval (ExtendScript has no native JSON).
    var t = String(text);
    var cleaned = t
      .replace(/\\(?:["\\\/bfnrt]|u[0-9a-fA-F]{4})/g, "@")
      .replace(/"[^"\\\n\r]*"|true|false|null|-?\d+(?:\.\d*)?(?:[eE][+\-]?\d+)?/g, "]")
      .replace(/(?:^|:|,)(?:\s*\[)+/g, "");
    if (!/^[\],:{}\s]*$/.test(cleaned)) {
      throw new Error("Invalid config payload.");
    }
    return eval("(" + t + ")");
  }

  function escStr(s) {
    return String(s).replace(/\\/g, "\\\\").replace(/"/g, "\\\"");
  }

  function pad2(n) { return (n < 10 ? "0" : "") + n; }

  function hexToRgb(hex) {
    var h = String(hex).replace("#", "");
    if (h.length === 3) {
      h = h.charAt(0) + h.charAt(0) + h.charAt(1) + h.charAt(1) + h.charAt(2) + h.charAt(2);
    }
    return [
      parseInt(h.substr(0, 2), 16) / 255,
      parseInt(h.substr(2, 2), 16) / 255,
      parseInt(h.substr(4, 2), 16) / 255
    ];
  }

  function round3(v) { return Math.round(v * 1000) / 1000; }

  // Pie angles need more precision — adjacent wedges share exact boundaries.
  function round6(v) { return Math.round(v * 1000000) / 1000000; }

  function thousandsStr(s) {
    var pt = String(s).split(".");
    var x = pt[0];
    var neg = x.charAt(0) === "-";
    if (neg) x = x.substr(1);
    var r = "";
    var c = 0;
    for (var i = x.length - 1; i >= 0; i--) {
      r = x.charAt(i) + r;
      c++;
      if (c % 3 === 0 && i > 0) r = "," + r;
    }
    return (neg ? "-" : "") + r + (pt.length > 1 ? "." + pt[1] : "");
  }

  // Static (non-animated) number formatting for axis ticks etc.
  function formatStatic(v, fmt, total) {
    if (fmt.mode === "percent") {
      return (total > 0 ? (v / total * 100) : 0).toFixed(1) + "%";
    }
    var s = v.toFixed(fmt.decimals);
    if (fmt.thousands) s = thousandsStr(s);
    return (fmt.prefix || "") + s + (fmt.suffix || "");
  }

  function niceStep(range, targetTicks) {
    if (range <= 0) return 1;
    var raw = range / targetTicks;
    var mag = Math.pow(10, Math.floor(Math.log(raw) / Math.LN10));
    var norm = raw / mag;
    var step;
    if (norm < 1.5) step = 1;
    else if (norm < 3) step = 2;
    else if (norm < 7) step = 5;
    else step = 10;
    return step * mag;
  }

  // ====================================================== expression text

  /* Shared timing preamble. Defines p (raw 0..1 progress for item `index`,
   * staggered) and e (eased progress; may exceed 1 for Overshoot). */
  function preamble(index) {
    return 'var C=thisComp.layer("' + CTRL_NAME + '");\n' +
      'var dur=Math.max(C.effect("ANIM | Build Duration")(1),0.01);\n' +
      'var stag=C.effect("ANIM | Stagger")(1);\n' +
      'var dly=C.effect("ANIM | Start Delay")(1);\n' +
      'var sty=Math.round(C.effect("ANIM | Easing Style")(1));\n' +
      'function easeP(q){\n' +
      ' if(sty<=1)return q;\n' +
      ' if(sty==2)return q*q*(3-2*q);\n' +
      ' if(sty==3){var s=1.70158,u=q-1;return 1+(s+1)*u*u*u+s*u*u;}\n' +
      ' var n1=7.5625,d1=2.75,u=q;\n' +
      ' if(u<1/d1)return n1*u*u;\n' +
      ' if(u<2/d1){u-=1.5/d1;return n1*u*u+0.75;}\n' +
      ' if(u<2.5/d1){u-=2.25/d1;return n1*u*u+0.9375;}\n' +
      ' u-=2.625/d1;return n1*u*u+0.984375;\n' +
      '}\n' +
      'var p=clamp((time-inPoint-dly-' + index + '*stag)/dur,0,1);\n' +
      // Animate-out: a shared factor that reverses the build so the chart
      // finishes leaving exactly at the layer's out point.
      'var oEn=C.effect("ANIM | Out Enabled")(1);\n' +
      'var oDur=Math.max(C.effect("ANIM | Out Duration")(1),0.01);\n' +
      'var o=(oEn>0)?easeP(clamp((outPoint-time)/oDur,0,1)):1;\n' +
      'var e=easeP(p)*o;\n';
  }

  /* Fade for static furniture (axes, ticks, legend, title): in at the start,
   * out with the animate-out window. mult lets ticks sit muted at 80. */
  function staticFadeExpr(useDelay, mult) {
    return 'var C=thisComp.layer("' + CTRL_NAME + '");\n' +
      (useDelay ? 'var dly=C.effect("ANIM | Start Delay")(1);\n' : '') +
      'var oEn=C.effect("ANIM | Out Enabled")(1);\n' +
      'var oDur=Math.max(C.effect("ANIM | Out Duration")(1),0.01);\n' +
      'var o=(oEn>0)?clamp((outPoint-time)/oDur,0,1):1;\n' +
      (useDelay
        ? 'clamp((time-inPoint-dly+0.25)/0.35,0,1)*o*' + mult
        : 'clamp((time-inPoint)/0.4,0,1)*o*' + mult);
  }

  /* Live color ramp: derive this item's tone from the master color.
   * t is the baked tone offset (-0.5..0.5); mult darkens (outlines). */
  function rampColorExpr(t, mult) {
    return 'var C=thisComp.layer("' + CTRL_NAME + '");\n' +
      'var mc=C.effect("COLOR | Master Color")(1);\n' +
      'var sp=C.effect("COLOR | Tone Spread")(1)/100;\n' +
      'var h=rgbToHsl(mc);\n' +
      'var t=' + round3(t) + ';\n' +
      'var l=clamp(h[2]+t*sp*0.7,0.08,0.94)*' + mult + ';\n' +
      'var s=clamp(h[1]-t*sp*0.25,0.05,1);\n' +
      'hslToRgb([h[0],s,clamp(l,0,1),1])';
  }

  function labelColorExpr() {
    return 'thisComp.layer("' + CTRL_NAME + '").effect("STYLE | Label Color")(1)';
  }

  function outlineWidthExpr() {
    return 'thisComp.layer("' + CTRL_NAME + '").effect("STYLE | Outline Width")(1)';
  }

  var THS_FN =
    'function ths(str){var pt=(""+str).split(".");var x=pt[0];var ng=x.charAt(0)=="-";' +
    'if(ng)x=x.substr(1);var r="";var c=0;for(var i=x.length-1;i>=0;i--){r=x.charAt(i)+r;c++;' +
    'if(c%3==0&&i>0)r=","+r;}return (ng?"-":"")+r+(pt.length>1?"."+pt[1]:"");}\n';

  /* Count-up label body: uses `e` from the preamble, emits `out`. */
  function countUpBody(value, total, fmt, progressVar) {
    var pv = progressVar || "e";
    if (fmt.mode === "percent") {
      var share = total > 0 ? (value / total * 100) : 0;
      return 'var out=(' + round3(share) + '*' + pv + ').toFixed(1)+"%";\n';
    }
    var core = 'v.toFixed(' + fmt.decimals + ')';
    if (fmt.thousands) core = 'ths(' + core + ')';
    return THS_FN +
      'var v=' + round3(value) + '*' + pv + ';\n' +
      'var out="' + escStr(fmt.prefix || "") + '"+' + core + '+"' + escStr(fmt.suffix || "") + '";\n';
  }

  // ======================================================== layer helpers

  function getComp() {
    var comp = app.project.activeItem;
    if (!(comp && comp instanceof CompItem)) {
      comp = app.project.items.addComp("Graphinator Chart", 1920, 1080, 1.0, 10, 29.97);
      comp.openInViewer();
    }
    return comp;
  }

  function findController(comp) {
    for (var i = 1; i <= comp.numLayers; i++) {
      var lay = comp.layer(i);
      if (lay.name === CTRL_NAME && String(lay.comment).indexOf(CTRL_TAG) === 0) return lay;
      if (lay.name === CTRL_NAME) return lay; // renamed comment, still ours
    }
    return null;
  }

  function removeItems(comp) {
    for (var i = comp.numLayers; i >= 1; i--) {
      var lay = comp.layer(i);
      if (String(lay.comment).indexOf(ITEM_TAG) === 0) {
        lay.locked = false;
        lay.remove();
      }
    }
  }

  function fxParade(layer) {
    return layer.property("ADBE Effect Parade");
  }

  /* Add an effect control if it doesn't exist yet. Returns the effect and
   * whether it was just created (so panel defaults only seed new controls). */
  function ensureFx(layer, matchName, dispName, defVal) {
    var parade = fxParade(layer);
    var existing = null;
    try { existing = parade.property(dispName); } catch (e) { existing = null; }
    if (existing) return { fx: existing, created: false };
    var fx = parade.addProperty(matchName);
    fx.name = dispName;
    if (defVal !== null && defVal !== undefined) fx.property(1).setValue(defVal);
    return { fx: fx, created: true };
  }

  function ensureEasingFx(layer, defIndex) {
    var parade = fxParade(layer);
    var existing = null;
    try { existing = parade.property("ANIM | Easing Style"); } catch (e) { existing = null; }
    if (existing) return;
    try {
      var dd = parade.addProperty("ADBE Dropdown Control");
      // setPropertyParameters invalidates references; use what it returns.
      var menu = dd.property(1).setPropertyParameters(["Linear", "Smooth", "Overshoot", "Bounce"]);
      var eff = menu.propertyGroup(1);
      eff.name = "ANIM | Easing Style";
      eff.property(1).setValue(defIndex);
    } catch (err) {
      // Older AE without scriptable dropdowns — fall back to a slider.
      var sl = parade.addProperty("ADBE Slider Control");
      sl.name = "ANIM | Easing Style";
      sl.property(1).setValue(defIndex);
    }
  }

  function ensureController(comp, cfg) {
    var ctrl = findController(comp);
    var isNew = false;
    if (!ctrl) {
      ctrl = comp.layers.addNull(comp.duration);
      ctrl.name = CTRL_NAME;
      ctrl.anchorPoint.setValue([0, 0]);
      ctrl.position.setValue([comp.width / 2, comp.height / 2]);
      ctrl.label = 10; // purple — stands out in the timeline
      isNew = true;
    }

    var master = hexToRgb(cfg.color.master);
    var defs = [
      ["ADBE Color Control", "COLOR | Master Color", [master[0], master[1], master[2], 1]],
      ["ADBE Slider Control", "COLOR | Tone Spread", cfg.color.spread],
      ["ADBE Slider Control", "ANIM | Start Delay", cfg.anim.delay],
      ["ADBE Slider Control", "ANIM | Build Duration", cfg.anim.duration],
      ["ADBE Slider Control", "ANIM | Stagger", cfg.anim.stagger],
      ["ADBE Checkbox Control", "ANIM | Out Enabled", cfg.anim.outEnabled ? 1 : 0],
      ["ADBE Slider Control", "ANIM | Out Duration", cfg.anim.outDuration || 1],
      ["ADBE Slider Control", "STYLE | Donut Hole %", (cfg.pie && cfg.pie.donutHole) || 0],
      ["ADBE Slider Control", "STYLE | Outline Width", 4],
      ["ADBE Slider Control", "STYLE | Line Weight", 8],
      ["ADBE Checkbox Control", "STYLE | Glow Enabled", 1],
      ["ADBE Slider Control", "STYLE | Glow Intensity", 0.35],
      ["ADBE Color Control", "STYLE | Label Color", [0.95, 0.95, 0.95, 1]],
      ["ADBE Slider Control", "SCALE | Overall Scale", 100]
    ];
    for (var i = 0; i < defs.length; i++) {
      ensureFx(ctrl, defs[i][0], defs[i][1], defs[i][2]);
    }
    ensureEasingFx(ctrl, EASING_INDEX[cfg.anim.easing] || 2);

    // Whole chart scales about the comp center from one slider.
    ctrl.scale.expression =
      'var s=effect("SCALE | Overall Scale")(1);\n[s,s]';

    return { ctrl: ctrl, isNew: isNew };
  }

  function readAnimValues(ctrl, cfg) {
    // Live values win over panel values so Update respects controller tweaks.
    var a = { delay: cfg.anim.delay, duration: cfg.anim.duration, stagger: cfg.anim.stagger };
    try { a.delay = ctrl.property("ADBE Effect Parade").property("ANIM | Start Delay").property(1).value; } catch (e1) {}
    try { a.duration = ctrl.property("ADBE Effect Parade").property("ANIM | Build Duration").property(1).value; } catch (e2) {}
    try { a.stagger = ctrl.property("ADBE Effect Parade").property("ANIM | Stagger").property(1).value; } catch (e3) {}
    return a;
  }

  function setMarkers(ctrl, startT, endT) {
    var mp = ctrl.property("ADBE Marker");
    while (mp.numKeys > 0) mp.removeKey(1);
    mp.setValueAtTime(startT, new MarkerValue("BUILD START — timing is live in this layer's ANIM effects. Markers refresh on Update."));
    mp.setValueAtTime(endT, new MarkerValue("BUILD COMPLETE"));
  }

  function storeData(ctrl, jsonStr) {
    ctrl.comment =
      CTRL_TAG + "\n" +
      "— Colors, timing, outline & scale: LIVE here (select me > Effect Controls).\n" +
      "— Data, chart type & formatting: Window > Extensions > Graphinator, then Update.\n" +
      "— Manual edits to generated layers are lost on Update.\n" +
      DATA_TAG + jsonStr;
  }

  function tagItem(layer, ctrl) {
    layer.comment = ITEM_COMMENT;
    layer.setParentWithJump(ctrl);
    // Deselect immediately — selected layers make AE reveal their freshly
    // scripted properties, leaving the timeline twirled open after a build.
    try { layer.selected = false; } catch (eSel) {}
  }

  function addShapeItem(comp, ctrl, name, labelColor) {
    var lay = comp.layers.addShape();
    lay.name = name;
    if (labelColor) { try { lay.label = labelColor; } catch (eL) {} }
    tagItem(lay, ctrl);
    return lay;
  }

  /* Resolve the configured family's PostScript names per weight via the
   * font API (AE 24+). boldIsFaux flags a family with no real bold style,
   * so bold text can fall back to synthetic bold. */
  var CHART_FONTS = null;

  function resolveFonts() {
    var out = { boldIsFaux: false };
    var weights = ["regular", "medium", "bold"];
    for (var i = 0; i < weights.length; i++) {
      var w = weights[i];
      var ps = null;
      var chosenStyle = null;
      try {
        var cands = FONT_STYLE_CANDIDATES[w];
        for (var j = 0; j < cands.length && !ps; j++) {
          var arr = app.fonts.getFontsByFamilyNameAndStyleName(FONT_FAMILY, cands[j]);
          if (arr && arr.length > 0) { ps = arr[0].postScriptName; chosenStyle = cands[j]; }
        }
      } catch (e) { ps = null; }
      if (w === "bold" && ps && chosenStyle === "Medium") out.boldIsFaux = true;
      out[w] = ps || FONT_FALLBACK_PS[w];
    }
    return out;
  }

  function addTextItem(comp, ctrl, name, str, fontSize, justification, weight, labelColor) {
    var lay = comp.layers.addText(str);
    lay.name = name;
    if (labelColor) { try { lay.label = labelColor; } catch (eL) {} }
    var tp = lay.property("ADBE Text Properties").property("ADBE Text Document");
    var td = tp.value;
    td.fontSize = fontSize;
    var w = weight || "medium";
    try { td.font = CHART_FONTS[w]; } catch (eFont) {}
    if (w === "bold" && CHART_FONTS.boldIsFaux) {
      try { td.fauxBold = true; } catch (eFaux) {}
    }
    td.applyFill = true;
    td.fillColor = [0.95, 0.95, 0.95];
    td.applyStroke = false;
    td.justification = justification;
    tp.setValue(td);
    tagItem(lay, ctrl);
    addLabelColorFx(lay);
    return lay;
  }

  function findFxProp(fx, matchName, dispName) {
    var p = null;
    try { p = fx.property(matchName); } catch (e1) { p = null; }
    if (!p) { try { p = fx.property(dispName); } catch (e2) { p = null; } }
    return p;
  }

  function setFxValue(fx, m, d, v) { var p = findFxProp(fx, m, d); if (p) { try { p.setValue(v); } catch (e) {} } }
  function setFxExpr(fx, m, d, ex) { var p = findFxProp(fx, m, d); if (p) { try { p.expression = ex; } catch (e) {} } }

  function applyColorSafe(prop, spec) {
    try { applyColor(prop, spec); } catch (e) {}
  }

  /* ---- Pro glow stack ----------------------------------------------------
   * AE's single Glow is weak, so stack three: tight core, medium spread,
   * wide fall-off — all in Add mode with A & B colors derived from the
   * item's tone. Every tier is gated by STYLE | Glow Enabled and scaled by
   * STYLE | Glow Intensity on the controller, so the whole stack switches
   * off with one checkbox. */
  function glowIntensityExpr(base) {
    return 'var C=thisComp.layer("' + CTRL_NAME + '");\n' +
      'var on=C.effect("STYLE | Glow Enabled")(1);\n' +
      'var m=Math.max(C.effect("STYLE | Glow Intensity")(1),0);\n' +
      'on>0?' + base + '*m:0';
  }

  function addOneGlow(layer, name, threshold, radius, baseIntensity, colorA, colorB) {
    try {
      var fx = fxParade(layer).addProperty("ADBE Glo2");
      fx.name = name;
      setFxValue(fx, "ADBE Glo2-0002", "Glow Threshold", threshold);
      setFxValue(fx, "ADBE Glo2-0003", "Glow Radius", radius);
      setFxExpr(fx, "ADBE Glo2-0004", "Glow Intensity", glowIntensityExpr(baseIntensity));
      setFxValue(fx, "ADBE Glo2-0006", "Glow Operation", 1); // Add
      setFxValue(fx, "ADBE Glo2-0007", "Glow Colors", 2);    // A & B Colors
      var pa = findFxProp(fx, "ADBE Glo2-0012", "Color A");
      var pb = findFxProp(fx, "ADBE Glo2-0013", "Color B");
      if (pa) applyColorSafe(pa, colorA);
      if (pb) applyColorSafe(pb, colorB);
    } catch (err) { /* glow is decorative — skip if unavailable */ }
  }

  function addGlowStack(layer, k, colors, full) {
    addOneGlow(layer, "Glow 1 — Tight Core", 65, 16 * k, 3.0, colors.highlight, colors.fill);
    if (full) {
      addOneGlow(layer, "Glow 2 — Medium Spread", 50, 100 * k, 1.0, colors.highlight, colors.fill);
      addOneGlow(layer, "Glow 3 — Wide Fall-off", 80, 500 * k, 0.5, colors.highlight, colors.fill);
    }
  }

  /* ---- Gradient shading ---------------------------------------------------
   * Shape gradient STOP colors aren't scriptable, so gradients are drawn in
   * plain white→black (geometry/direction IS scriptable) and a Tritone
   * effect remaps luminance to this item's highlight/body/shadow tones —
   * which are expression-linked to the master color, keeping gradients
   * fully live. White art (caps, rims) maps to Highlights; black strokes
   * map to Shadows. */
  function addTritoneFx(layer, colors) {
    try {
      var fx = fxParade(layer).addProperty("ADBE Tritone");
      fx.name = "Tone Map — drives gradient colors";
      var hi = findFxProp(fx, "ADBE Tritone-0001", "Highlights");
      var mid = findFxProp(fx, "ADBE Tritone-0002", "Midtones");
      var sh = findFxProp(fx, "ADBE Tritone-0003", "Shadows");
      if (hi) applyColorSafe(hi, colors.highlight);
      if (mid) applyColorSafe(mid, colors.fill);
      if (sh) applyColorSafe(sh, colors.outline);
    } catch (err) {}
  }

  /* Fill effect so every label follows the controller's Label Color live. */
  function addLabelColorFx(layer) {
    try {
      var fx = fxParade(layer).addProperty("ADBE Fill");
      var col = null;
      try { col = fx.property("ADBE Fill-0002"); } catch (e1) { col = null; }
      if (!col) col = fx.property("Color");
      col.expression = labelColorExpr();
    } catch (err) { /* label stays static near-white — acceptable fallback */ }
  }

  function addGroupWithPath(layer, groupName, shape, closed) {
    var grp = layer.property("ADBE Root Vectors Group").addProperty("ADBE Vector Group");
    grp.name = groupName;
    var cont = grp.property("ADBE Vectors Group");
    var pathProp = cont.addProperty("ADBE Vector Shape - Group");
    var sh = new Shape();
    sh.vertices = shape;
    sh.closed = !!closed;
    pathProp.property("ADBE Vector Shape").setValue(sh);
    return cont;
  }

  function addStroke(cont, widthOrExpr, colorExprOrValue, capButt) {
    var st = cont.addProperty("ADBE Vector Graphic - Stroke");
    if (typeof widthOrExpr === "string") st.property("ADBE Vector Stroke Width").expression = widthOrExpr;
    else st.property("ADBE Vector Stroke Width").setValue(widthOrExpr);
    if (typeof colorExprOrValue === "string") st.property("ADBE Vector Stroke Color").expression = colorExprOrValue;
    else st.property("ADBE Vector Stroke Color").setValue(colorExprOrValue);
    if (capButt) {
      try { st.property("ADBE Vector Stroke Line Cap").setValue(1); } catch (e) {}
    }
    return st;
  }

  function itemTone(i, n) {
    return n > 1 ? (i / (n - 1) - 0.5) : 0;
  }

  function itemFillColorSpec(cfg, i, n) {
    // Returns {expr:...} for ramped tones or {value:[r,g,b,a]} for overrides.
    // fill = body tone, outline = darkened edge, highlight = brightened sheen.
    var it = cfg.items[i];
    if (it.useCustom) {
      var rgb = hexToRgb(it.color);
      return { fill: { value: [rgb[0], rgb[1], rgb[2], 1] },
               outline: { value: [rgb[0] * 0.55, rgb[1] * 0.55, rgb[2] * 0.55, 1] },
               highlight: { value: [Math.min(rgb[0] * 1.5 + 0.08, 1), Math.min(rgb[1] * 1.5 + 0.08, 1), Math.min(rgb[2] * 1.5 + 0.08, 1), 1] } };
    }
    var t = itemTone(i, n);
    return { fill: { expr: rampColorExpr(t, 1) },
             outline: { expr: rampColorExpr(t, 0.55) },
             highlight: { expr: rampColorExpr(t, 1.5) } };
  }

  function applyColor(prop, spec) {
    if (spec.expr) prop.expression = spec.expr;
    else prop.setValue(spec.value);
  }

  function sum(items) {
    var s = 0;
    for (var i = 0; i < items.length; i++) s += items[i].value;
    return s;
  }

  function maxVal(items) {
    var m = 0;
    for (var i = 0; i < items.length; i++) if (items[i].value > m) m = items[i].value;
    return m;
  }

  // =================================================== axes / grid / text

  /* Normalize bar/line/area data to {categories, series, overrides}.
   * Accepts the v2 shape (categories + series[]) or legacy items[]. */
  function normalizeSeries(cfg) {
    if (cfg.series && cfg.categories) {
      return {
        categories: cfg.categories,
        series: cfg.series,
        overrides: cfg.pointOverrides || []
      };
    }
    var cats = [], vals = [], ovr = [];
    for (var i = 0; i < cfg.items.length; i++) {
      cats.push(cfg.items[i].label);
      vals.push(cfg.items[i].value);
      ovr.push({ useCustom: !!cfg.items[i].useCustom, color: cfg.items[i].color });
    }
    return { categories: cats, series: [{ name: cfg.seriesName || "Series 1", values: vals }], overrides: ovr };
  }

  /* Value-axis range covering all series, negatives included, snapped to a
   * nice step and always spanning zero. */
  function computeAxis(seriesArr) {
    var maxV = 0, minV = 0;
    for (var j = 0; j < seriesArr.length; j++) {
      var vv = seriesArr[j].values;
      for (var i = 0; i < vv.length; i++) {
        if (vv[i] > maxV) maxV = vv[i];
        if (vv[i] < minV) minV = vv[i];
      }
    }
    if (maxV === 0 && minV === 0) maxV = 1;
    var step = niceStep(maxV - minV, 5);
    var niceMax = Math.ceil(maxV / step) * step;
    var niceMin = Math.floor(minV / step) * step;
    if (niceMax === niceMin) niceMax = niceMin + step;
    return { min: niceMin, max: niceMax, step: step, range: niceMax - niceMin };
  }

  function grandTotal(seriesArr) {
    var t = 0;
    for (var j = 0; j < seriesArr.length; j++) {
      for (var i = 0; i < seriesArr[j].values.length; i++) t += seriesArr[j].values[i];
    }
    return t === 0 ? 1 : t;
  }

  /* Color spec (fill/outline/highlight) for a series datum: per-point tones
   * in single-series mode (with per-point overrides), per-series tones when
   * there are multiple series. */
  function seriesColorSpec(data, i, j) {
    var m = data.series.length, n = data.categories.length;
    if (m === 1 && data.overrides[i] && data.overrides[i].useCustom) {
      var rgb = hexToRgb(data.overrides[i].color);
      return { fill: { value: [rgb[0], rgb[1], rgb[2], 1] },
               outline: { value: [rgb[0] * 0.55, rgb[1] * 0.55, rgb[2] * 0.55, 1] },
               highlight: { value: [Math.min(rgb[0] * 1.5 + 0.08, 1), Math.min(rgb[1] * 1.5 + 0.08, 1), Math.min(rgb[2] * 1.5 + 0.08, 1), 1] } };
    }
    var t = m > 1 ? itemTone(j, m) : itemTone(i, n);
    return { fill: { expr: rampColorExpr(t, 1) },
             outline: { expr: rampColorExpr(t, 0.55) },
             highlight: { expr: rampColorExpr(t, 1.5) } };
  }

  /* Gridlines, zero line, borders, and tick labels along the value axis.
   * horizontal=false → value axis is Y (ticks left); true → X (ticks below). */
  function buildValueAxis(comp, ctrl, geo, axis, fmt, total, horizontal) {
    var left = geo.left, right = geo.right, base = geo.base, top = geo.top, k = geo.k;

    var axes = addShapeItem(comp, ctrl, "Axes & Gridlines", LC.axes);
    axes.position.setValue([0, 0]);

    var ticks = Math.max(1, Math.round(axis.range / axis.step));
    var j, tv, cont, st;
    for (j = 0; j <= ticks; j++) {
      tv = axis.min + axis.step * j;
      var frac = (tv - axis.min) / axis.range;
      var pathPts = horizontal
        ? [[left + geo.pw * frac, top], [left + geo.pw * frac, base]]
        : [[left, base - geo.ph * frac], [right, base - geo.ph * frac]];
      var isZero = Math.abs(tv) < axis.step * 0.001;
      cont = addGroupWithPath(axes, (isZero ? "Zero Line " : "Gridline ") + formatStatic(tv, fmt, total), pathPts, false);
      st = addStroke(cont, (isZero ? 3 : 2) * k, labelColorExpr(), false);
      if (!isZero) st.property("ADBE Vector Stroke Opacity").setValue(22);
    }

    // Category-axis border.
    var borderPts = horizontal
      ? [[left, base], [left, top]]
      : [[left, base], [right, base]];
    cont = addGroupWithPath(axes, "Category Axis", borderPts, false);
    st = addStroke(cont, 2 * k, labelColorExpr(), false);
    st.property("ADBE Vector Stroke Opacity").setValue(60);

    axes.opacity.expression = staticFadeExpr(true, 100);

    // Tick value labels — the quietest tier of the type scale.
    for (j = 0; j <= ticks; j++) {
      tv = axis.min + axis.step * j;
      var frac2 = (tv - axis.min) / axis.range;
      var lab = addTextItem(comp, ctrl, "Tick — " + formatStatic(tv, fmt, total),
        formatStatic(tv, fmt, total), 22 * k,
        horizontal ? ParagraphJustification.CENTER_JUSTIFY : ParagraphJustification.RIGHT_JUSTIFY,
        "regular", LC.tick);
      if (horizontal) lab.position.setValue([left + geo.pw * frac2, base + 36 * k]);
      else lab.position.setValue([left - 16 * k, base - geo.ph * frac2 + 8 * k]);
      lab.opacity.expression = staticFadeExpr(true, 80);
    }
  }

