  function generate(jsonStr) {
    var undoOpen = false;
    try {
      var cfg = parseJSON(jsonStr);
      if (!cfg || !cfg.items || cfg.items.length < 2) return "ERR|Need at least 2 data points.";

      app.beginUndoGroup("Graphinator: Generate Chart");
      undoOpen = true;

      var comp = getComp();
      var k = Math.min(comp.width / 1920, comp.height / 1080);
      CHART_FONTS = resolveFonts();

      removeItems(comp);
      var res = ensureController(comp, cfg);
      var ctrl = res.ctrl;

      if (cfg.type === "bar") buildBar(comp, ctrl, cfg, k);
      else if (cfg.type === "line") buildLine(comp, ctrl, cfg, k, false);
      else if (cfg.type === "area") buildLine(comp, ctrl, cfg, k, true);
      else if (cfg.type === "pie") buildPie(comp, ctrl, cfg, k);
      else return "ERR|Unknown chart type: " + cfg.type;

      // Markers reflect the timing in force right now (live values if the
      // controller already existed). Refreshed on every Update.
      var anim = readAnimValues(ctrl, cfg);
      var startT = anim.delay;
      var nPts = cfg.categories ? cfg.categories.length : cfg.items.length;
      var mSer = cfg.series ? cfg.series.length : 1;
      var endT;
      if (cfg.type === "bar") endT = anim.delay + anim.duration + anim.stagger * ((nPts - 1) + (mSer - 1) * 0.25);
      else if (cfg.type === "line" || cfg.type === "area") endT = anim.delay + anim.duration + anim.stagger * (mSer - 1) + 0.3;
      else endT = anim.delay + anim.duration + 0.6; // pie: single sweep + label tail
      setMarkers(ctrl, startT, endT);

      storeData(ctrl, jsonStr);
      ctrl.moveToBeginning();

      // Leave the timeline tidy: nothing selected, all layers collapsed.
      for (var li = 1; li <= comp.numLayers; li++) {
        try { comp.layer(li).selected = false; } catch (eDesel) {}
      }

      app.endUndoGroup();
      undoOpen = false;

      var msg = "Built " + cfg.type + " chart with " + cfg.items.length + " points in \"" + comp.name + "\". " +
        (res.isNew
          ? "Colors, timing & scale are now live on the controller layer."
          : "Controller kept — your live color/timing tweaks were preserved.");
      return "OK|" + msg;
    } catch (err) {
      if (undoOpen) { try { app.endUndoGroup(); } catch (e2) {} }
      return "ERR|" + (err && err.message ? err.message : String(err)) + (err && err.line ? " (jsx line " + err.line + ")" : "");
    }
  }

  function readData() {
    try {
      var comp = app.project.activeItem;
      if (!(comp && comp instanceof CompItem)) return "ERR|Open the comp that contains a Graphinator chart first.";
      var ctrl = findController(comp);
      if (!ctrl) return "ERR|No \"" + CTRL_NAME + "\" layer found in this comp.";
      var c = String(ctrl.comment);
      var idx = c.indexOf(DATA_TAG);
      if (idx < 0) return "ERR|The controller has no stored chart data.";
      return "DATA|" + c.substring(idx + DATA_TAG.length);
    } catch (err) {
      return "ERR|" + (err && err.message ? err.message : String(err));
    }
  }

